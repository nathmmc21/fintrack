# ---------------------------------------------------------------- security prices
prices = APIRouter(prefix="/api/securities", tags=["securities"])


@prices.get("/{security_id}/prices", dependencies=[Depends(current_user)])
def list_prices(security_id: int):
    with db() as cur:
        cur.execute(
            "SELECT price_date, close_price FROM security_prices WHERE security_id = %s "
            "ORDER BY price_date DESC LIMIT 365", (security_id,))
        return cur.fetchall()


@prices.post("/{security_id}/prices", status_code=201, dependencies=[Depends(staff_only)])
def upsert_price(security_id: int, body: PriceIn):
    with db() as cur:
        cur.execute(
            """INSERT INTO security_prices (security_id, price_date, close_price) VALUES (%s, %s, %s)
               ON CONFLICT (security_id, price_date) DO UPDATE SET close_price = EXCLUDED.close_price
               RETURNING security_id, price_date, close_price""",
            (security_id, body.price_date, body.close_price))
        return cur.fetchone()


# ---------------------------------------------------------------- categories
categories = APIRouter(prefix="/api/categories", tags=["categories"])
CAT_COLS = "id, name, kind, user_id IS NULL AS is_system"


def _is_staff(user: dict) -> bool:
    return user["role"] in ("admin", "staff")


@categories.get("")
def list_categories(user: dict = Depends(current_user)):
    with db() as cur:
        cur.execute(
            f"SELECT {CAT_COLS} FROM categories WHERE user_id IS NULL OR user_id = %s ORDER BY kind, name",
            (user["id"],))
        return cur.fetchall()


@categories.post("", status_code=201)
def create_category(body: CategoryIn, user: dict = Depends(current_user)):
    if body.is_system and not _is_staff(user):
        raise HTTPException(403, "Only staff can create system-wide categories")
    owner = None if body.is_system else user["id"]
    with db() as cur:
        cur.execute(
            f"INSERT INTO categories (user_id, name, kind) VALUES (%s, %s, %s) RETURNING {CAT_COLS}",
            (owner, body.name.strip(), body.kind))
        return cur.fetchone()


@categories.put("/{category_id}")
def update_category(category_id: int, body: CategoryIn, user: dict = Depends(current_user)):
    with db() as cur:
        cur.execute(
            f"""UPDATE categories SET name = %s, kind = %s
                WHERE id = %s AND (user_id = %s OR (user_id IS NULL AND %s))
                RETURNING {CAT_COLS}""",
            (body.name.strip(), body.kind, category_id, user["id"], _is_staff(user)))
        row = cur.fetchone()
    if not row:
        raise HTTPException(404, "Category not found, or you may not edit it")
    return row


@categories.delete("/{category_id}", status_code=204)
def delete_category(category_id: int, user: dict = Depends(current_user)):
    with db() as cur:
        cur.execute(
            "DELETE FROM categories WHERE id = %s AND (user_id = %s OR (user_id IS NULL AND %s)) RETURNING id",
            (category_id, user["id"], _is_staff(user)))
        if not cur.fetchone():
            raise HTTPException(404, "Category not found, or you may not delete it")
    return Response(status_code=204)


# ---------------------------------------------------------------- keyword rules
rules = APIRouter(prefix="/api/category-rules", tags=["categorisation rules"])


@rules.get("")
def list_rules(user: dict = Depends(current_user)):
    with db() as cur:
        cur.execute(
            """SELECT r.id, r.keyword, r.category_id, c.name AS category, r.user_id IS NULL AS is_system
               FROM category_rules r JOIN categories c ON c.id = r.category_id
               WHERE r.user_id IS NULL OR r.user_id = %s ORDER BY r.keyword""", (user["id"],))
        return cur.fetchall()


@rules.post("", status_code=201)
def create_rule(body: RuleIn, user: dict = Depends(current_user)):
    if body.is_system and not _is_staff(user):
        raise HTTPException(403, "Only staff can create system-wide rules")
    owner = None if body.is_system else user["id"]
    with db() as cur:
        cur.execute(     # only categories the user is allowed to use can be targeted
            """INSERT INTO category_rules (user_id, keyword, category_id)
               SELECT %s, %s, c.id FROM categories c
               WHERE c.id = %s AND (c.user_id IS NULL OR c.user_id = %s)
               RETURNING id, keyword, category_id""",
            (owner, body.keyword.strip(), body.category_id, user["id"]))
        row = cur.fetchone()
    if not row:
        raise HTTPException(400, "Unknown category")
    return row


@rules.delete("/{rule_id}", status_code=204)
def delete_rule(rule_id: int, user: dict = Depends(current_user)):
    with db() as cur:
        cur.execute(
            "DELETE FROM category_rules WHERE id = %s AND (user_id = %s OR (user_id IS NULL AND %s)) RETURNING id",
            (rule_id, user["id"], _is_staff(user)))
        if not cur.fetchone():
            raise HTTPException(404, "Rule not found, or you may not delete it")
    return Response(status_code=204)
